import numpy as np
def cb(x1,y1,x2,y2):
    def f(x):
        if x<=0: return 0.0
        if x>=1: return 1.0
        lo,hi,t=0.0,1.0,x
        for _ in range(50):
            cx=3*x1; bx=3*(x2-x1)-cx; ax=1-cx-bx
            xt=((ax*t+bx)*t+cx)*t
            if abs(xt-x)<1e-7: break
            if xt<x: lo=t
            else: hi=t
            t=(lo+hi)/2
        cy=3*y1; by=3*(y2-y1)-cy; ay=1-cy-by
        return ((ay*t+by)*t+cy)*t
    return f

